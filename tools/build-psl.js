/**
 * Rebuilds lib/psl.js from the Public Suffix List (https://publicsuffix.org, MPL 2.0).
 *   curl -o public_suffix_list.dat https://publicsuffix.org/list/public_suffix_list.dat
 *   node tools/build-psl.js public_suffix_list.dat
 * Single-label rules ("com", "fr") are left out: one label is the default.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const source = process.argv[2];
if (!source) { console.error('Usage: node tools/build-psl.js <public_suffix_list.dat>'); process.exit(1); }

const toAscii = (rule) => new URL('http://' + rule).hostname;
const rules = new Set();
const wild = new Set();
const except = new Set();

fs.readFileSync(source, 'utf8').split(/\r?\n/).forEach((line) => {
  const rule = line.trim().split(/\s/)[0];
  if (!rule || rule.startsWith('//')) return;
  try {
    if (rule.startsWith('!')) except.add(toAscii(rule.slice(1)));
    else if (rule.startsWith('*.')) wild.add(toAscii(rule.slice(2)));
    else if (rule.includes('.')) rules.add(toAscii(rule));
  } catch (e) { /* not a valid hostname: skip */ }
});

const pack = (set) => JSON.stringify(Array.from(set).sort().join(' '));
const out = `/*
 * Public Suffix List (https://publicsuffix.org), Mozilla Public License 2.0.
 * Generated by tools/build-psl.js on ${new Date().toISOString().slice(0, 10)}: do not edit by hand.
 * Tells where a site name really starts: "x.co.uk" belongs to "x", not to "co.uk".
 */
(function (root) {
  'use strict';
  const api = {
    rules: ${pack(rules)},
    wild: ${pack(wild)},
    except: ${pack(except)}
  };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.ShowYourselfPSL = api;
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'psl.js'), out);
console.log(rules.size + ' rules, ' + wild.size + ' wildcards, ' + except.size + ' exceptions');
