  function detect() {
    let lang = '';
    try { if (typeof chrome !== 'undefined' && chrome.i18n) lang = chrome.i18n.getUILanguage(); } catch (e) { /* ignore */ }
    if (!lang && typeof navigator !== 'undefined') lang = navigator.language || '';
    if (!lang) return 'fr'; // Node (unit tests)
    return /^fr/i.test(lang) ? 'fr' : 'en';
  }

  let current = detect();

  function t(key, params) {
    const dict = MESSAGES[current];
    let s = dict[key] !== undefined ? dict[key] : (MESSAGES.en[key] !== undefined ? MESSAGES.en[key] : key);
    if (params) s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] !== undefined ? String(params[k]) : m; });
    return s;
  }

  /** Fills every [data-i18n] element of a page (popup, welcome). */
  function translatePage(doc) {
    doc.documentElement.lang = current;
    doc.querySelectorAll('[data-i18n]').forEach(function (node) { node.textContent = t(node.getAttribute('data-i18n')); });
  }

  return {
    t: t,
    translatePage: translatePage,
    getLang: function () { return current; },
    setLang: function (l) { if (MESSAGES[l]) current = l; }
  };
